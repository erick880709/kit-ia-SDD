// Ajv and esbuild are build dependencies only. The emitted ESM has no imports.
import fs from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import Ajv from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { unicodeNonspace } from "../rules.mjs";
import { _ } from "ajv/dist/compile/codegen/index.js";
import { uri } from "./uri-format.mjs";
const schemaURL = new URL("../schemas/result.schema.json", import.meta.url);
const bytes = fs.readFileSync(schemaURL);
const schema = JSON.parse(bytes);
// Translate the regex dialect without changing the source schema's meaning.
function translatePatterns(v) {
  if (!v || typeof v !== "object") return;
  for (const [key, value] of Object.entries(v)) {
    if (key === "pattern" && typeof value === "string")
      v[key] = value.replaceAll("\\S", unicodeNonspace);
    else translatePatterns(value);
  }
}
translatePatterns(schema);
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
addFormats(ajv);
ajv.addFormat("uri", uri);
ajv.opts.code.formats = _`require("./scripts/uri-format.mjs")`;
ajv.addSchema(schema);
ajv.addSchema({
  $id: "urn:kit-ia:uri",
  ...schema.$defs.artifact.properties.uri,
});
const code = standalone.default(ajv, {
  resultSchema: schema.$id,
  uriSchema: "urn:kit-ia:uri",
});
const bundled = await build({
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  stdin: {
    contents: code,
    resolveDir: fileURLToPath(new URL("../", import.meta.url)),
    loader: "js",
  },
  bundle: true,
  write: false,
  platform: "node",
  format: "esm",
  legalComments: "none",
});
// El hash ignora finales de línea: el checkout puede convertir LF a CRLF sin cambiar el schema.
const hash = createHash("sha256").update(bytes.toString("utf8").replace(/\r\n/g, "\n")).digest("hex");
const notices = ['ajv', 'ajv-formats', 'fast-deep-equal', 'esbuild'].map(name => {
  const license = name === 'esbuild' ? 'LICENSE.md' : 'LICENSE';
  return `${name}\n${fs.readFileSync(new URL(`../node_modules/${name}/${license}`, import.meta.url), 'utf8')}`;
});
fs.writeFileSync(
  new URL("../schemas/result.validate.mjs", import.meta.url),
  `// Generated by scripts/generate-validator.mjs; do not edit.\n/*\nThird-party licenses\n${notices.join('\n\n')}\n*/\nexport const schemaSha256 = '${hash}';\n${bundled.outputFiles[0].text}`,
);
