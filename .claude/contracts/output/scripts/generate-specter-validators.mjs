// Genera validadores JSON Schema standalone para los contratos de Specter
// (user-story.schema.json y technical-task.schema.json) usando ajv standalone + esbuild.
// Igual que scripts/generate-validator.mjs pero para las dos capacidades de Specter.
// Salida: .claude/skills/specter/contracts/specter-schemas.validate.mjs (sin imports).
import fs from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import Ajv from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { unicodeNonspace } from "../rules.mjs";

const huURL = new URL("../../../skills/specter/contracts/user-story.schema.json", import.meta.url);
const ttURL = new URL("../../../skills/specter/contracts/technical-task.schema.json", import.meta.url);

const huBytes = fs.readFileSync(huURL);
const ttBytes = fs.readFileSync(ttURL);
const huSchema = JSON.parse(huBytes);
const ttSchema = JSON.parse(ttBytes);

function translatePatterns(v) {
  if (!v || typeof v !== "object") return;
  for (const [key, value] of Object.entries(v)) {
    if (key === "pattern" && typeof value === "string") v[key] = value.replaceAll("\\S", unicodeNonspace);
    else translatePatterns(value);
  }
}
translatePatterns(huSchema);
translatePatterns(ttSchema);

const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(huSchema);
ajv.addSchema(ttSchema);

const code = standalone.default(ajv, {
  validateStory: huSchema.$id,
  validateTask: ttSchema.$id,
});

const bundled = await build({
  absWorkingDir: fileURLToPath(new URL("../", import.meta.url)),
  stdin: { contents: code, resolveDir: fileURLToPath(new URL("../", import.meta.url)), loader: "js" },
  bundle: true,
  write: false,
  platform: "node",
  format: "esm",
  legalComments: "none",
});

const hashOf = bytes => createHash("sha256").update(bytes.toString("utf8").replace(/\r\n/g, "\n")).digest("hex");
const out = new URL("../../../skills/specter/contracts/specter-schemas.validate.mjs", import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by scripts/generate-specter-validators.mjs; do not edit.\nexport const userStorySchemaSha256 = '${hashOf(huBytes)}';\nexport const technicalTaskSchemaSha256 = '${hashOf(ttBytes)}';\n${bundled.outputFiles[0].text}`,
);
console.log("Generado:", fileURLToPath(out));
